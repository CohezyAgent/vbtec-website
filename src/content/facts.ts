/** Haal een feit op via key (typesafe). */
export function fact(key: FactKey): Fact {
  const f = FACT_MAP.get(key);
  if (!f) throw new Error(`Onbekend feit: ${key}`);
  return f;
}

/** Formatteer een getal in nl-BE (bv. 0,3 → "0,30"). */
export function formatFactValue(f: Fact, opts?: Intl.NumberFormatOptions): string {
  const n = new Intl.NumberFormat("nl-BE", { maximumFractionDigits: 3, ...opts });
  const v = f.range ? `${n.format(f.range[0])}–${n.format(f.range[1])}` : n.format(f.value);
  return `${f.estimate ? "ca. " : ""}${v}`;
}

